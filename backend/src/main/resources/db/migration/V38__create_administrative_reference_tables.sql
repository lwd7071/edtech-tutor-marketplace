-- V38: Vietnamese administrative reference tables (2025 two-level structure)
-- Source: Open Admin Data, derived from Decision 19/2025 and NSO counts.

CREATE TABLE provinces (
    code        varchar(2) primary key,
    name        varchar(120) not null,
    is_active   boolean not null default true,
    constraint ck_provinces_code_format check (code ~ '^[0-9]{2}$'),
    constraint uq_provinces_name unique (name)
);

CREATE TABLE wards (
    code          varchar(5) primary key,
    province_code varchar(2) not null references provinces(code),
    name          varchar(160) not null,
    is_active     boolean not null default true,
    constraint ck_wards_code_format check (code ~ '^[0-9]{5}$'),
    constraint uq_wards_province_name unique (province_code, name),
    constraint uq_wards_code_province unique (code, province_code)
);

CREATE INDEX ix_wards_province_code ON wards (province_code);

